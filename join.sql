SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.ORDER_DATE,
    O.TOTAL_AMOUNT,
    O.ORDER_STATUS
FROM CUSTOMER C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.TOTAL_AMOUNT,
    O.ORDER_STATUS
FROM CUSTOMER C
LEFT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.TOTAL_AMOUNT,
    O.ORDER_STATUS
FROM CUSTOMER C
RIGHT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.ORDER_DATE,
    O.TOTAL_AMOUNT,
    O.ORDER_STATUS
FROM CUSTOMER C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
ORDER BY C.CUSTOMER_ID, O.ORDER_DATE;

SELECT
    O.ORDER_ID,
    O.TOTAL_AMOUNT,
    O.ORDER_STATUS,
    PAY.PAYMENT_MODE,
    PAY.PAYMENT_AMOUNT,
    PAY.PAYMENT_STATUS
FROM ORDERS O
INNER JOIN PAYMENT PAY
ON O.ORDER_ID = PAY.ORDER_ID
ORDER BY O.ORDER_ID;

SELECT
    C.CUSTOMER_NAME,
    O.ORDER_ID,
    O.ORDER_DATE,
    P.PRODUCT_NAME,
    OD.QUANTITY,
    O.TOTAL_AMOUNT,
    O.ORDER_STATUS,
    PAY.PAYMENT_MODE,
    PAY.PAYMENT_STATUS
FROM CUSTOMER C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
LEFT JOIN ORDER_DETAILS OD
ON O.ORDER_ID = OD.ORDER_ID
LEFT JOIN PRODUCT P
ON OD.PRODUCT_ID = P.PRODUCT_ID
LEFT JOIN PAYMENT PAY
ON O.ORDER_ID = PAY.ORDER_ID
ORDER BY O.ORDER_ID;