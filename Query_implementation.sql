    OD.ORDER_ID,
    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    OD.QUANTITY
FROM ORDER_DETAILS OD, PRODUCT P
WHERE OD.PRODUCT_ID = P.PRODUCT_ID
ORDER BY OD.ORDER_ID;

SELECT
    CUSTOMER_ID,
    COUNT(*) AS TOTAL_ORDERS
FROM ORDERS
GROUP BY CUSTOMER_ID
ORDER BY TOTAL_ORDERS DESC;

